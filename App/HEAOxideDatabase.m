            T_K = T_C + 273.15;
            ranked = HEAOxideDatabase.rankOxidesByAffinity(elements, T_K);
            
            n = numel(ranked);
            formulas = {ranked.Formula}';
            names    = {ranked.Name}';
            classes  = {ranked.Class}';
            pbrs     = [ranked.PBR]';
            densities= [ranked.Density]';
            dG_kJ    = zeros(n, 1);
            for i = 1:n
                dG_kJ(i) = round(HEAOxideDatabase.computeDeltaG(ranked(i), T_K), 1);
            end

            tbl = table(formulas, names, dG_kJ, pbrs, densities, classes, ...
                'VariableNames', {'Oxide', 'Name', 'DeltaG_f_kJ_per_mol_O2', 'PBR', 'Density_g_cm3', 'Scale_Classification'});
        end

