        function candidateOxides = getOxidesForElements(elements)
            candidateOxides = HEAOxideDatabase.getOxidesForAlloy(elements);
        end

        function candidateOxides = getOxidesForAlloy(elements)
            % Returns all possible candidate oxides whose metal constituents exist in the current alloy
            allOx = HEAOxideDatabase.getAllOxides();
            nAll = numel(allOx);
            isMatch = false(nAll, 1);
            
            cleanElems = cellfun(@strtrim, elements, 'UniformOutput', false);

            for i = 1:nAll
                req = allOx(i).Elements;
                % All constituent metal elements must be present in the alloy
                if all(ismember(req, cleanElems))
                    isMatch(i) = true;
                end
            end

            candidateOxides = allOx(isMatch);
            % Fallback: if no binary/spinel matches (e.g. exotic alloy), return at least common protective ones
            if isempty(candidateOxides)
                candidateOxides = allOx(1:3);
            end
        end

        function dG_kJ = computeDeltaG(oxideStruct, T_K)
            % Computes Delta G_f(T) in kJ / mol O2
            dG_J = oxideStruct.A + oxideStruct.B * T_K;
            dG_kJ = dG_J * 1e-3;
        end

        function ranked = rankOxidesByAffinity(elements, T_K)
            % Returns candidate oxides sorted by oxygen affinity (most negative Delta G_f first)
            cand = HEAOxideDatabase.getOxidesForAlloy(elements);
            n = numel(cand);
            dGVals = zeros(n, 1);
            for i = 1:n
                dGVals(i) = HEAOxideDatabase.computeDeltaG(cand(i), T_K);
            end
            [~, sIdx] = sort(dGVals, 'ascend');
            ranked = cand(sIdx);
        end

